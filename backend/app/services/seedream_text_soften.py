"""Seedream 输入文案软化：保留主体语义，降低 InputTextSensitive 误杀。

不做空主体 / CG 厚涂兜底；仅替换易触发审核的未成年人、酒精、兵器与网红等表述。
"""

from __future__ import annotations

# 长词优先，避免短词先替换破坏短语
_SEEDREAM_TEXT_SOFTEN: list[tuple[str, str]] = [
    # 酒精 / 配饰
    ("腰悬酒葫芦", "腰佩圆润如意饰"),
    ("酒葫芦", "腰间圆润如意饰"),
    ("葫芦形佩饰", "腰间圆润如意饰"),
    ("葫芦", "圆润佩饰"),
    ("醉酒", "微醺神态"),
    ("饮酒", "持盏"),
    ("悬酒", "腰佩"),
    # 未成年人 / 校园
    ("现代课堂学生", "学堂少年学子"),
    ("课堂学生", "学堂学子"),
    ("毛毡小人", "毛毡玩偶"),
    ("小学男生", "少年学子"),
    ("小学女生", "少年学子"),
    ("小学生", "少年学子"),
    ("婴幼儿", "幼龄角色"),
    ("幼童", "少年"),
    ("儿童", "少年"),
    ("小孩", "少年"),
    ("孩子", "少年"),
    ("童声", "清亮稚气嗓音"),
    ("童真", "天真好奇"),
    ("校服", "学院制服"),
    ("课堂", "学堂"),
    ("学生", "学子"),
    # 兵器 / 网红 / 名号
    ("白衣佩剑", "白衣腰佩长绦"),
    ("腰佩长剑", "腰佩长绦"),
    ("佩剑", "腰佩长绦"),
    ("顶流", "名士"),
    ("诗仙", "盛唐豪放诗人"),
]


# 软化易触发 Seedream 文本审核的措辞；无变化则原样返回
def soften_seedream_input_text(prompt: str) -> str:
    out = prompt or ""
    if not out:
        return out
    for src, dst in _SEEDREAM_TEXT_SOFTEN:
        if src in out:
            out = out.replace(src, dst)
    return out
